#!/usr/bin/env node
/**
 * Build society plugins into ESM for real dsh --patch loading, and write
 * profiles/dsh-society/cordis.patch.yml with absolute path inserts.
 *
 * Usage: node scripts/build-dsh-overlay.mjs
 * After clone on another machine, re-run so absolute paths match that checkout.
 */
import * as esbuild from 'esbuild'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT_DIR = path.join(ROOT, 'profiles', 'dsh-society', 'lib')
const PATCH_OUT = path.join(ROOT, 'profiles', 'dsh-society', 'cordis.patch.yml')
const TEMPLATE_OUT = path.join(ROOT, 'profiles', 'dsh-society', 'cordis.patch.template.yml')

const PLUGINS = [
  'society-identity',
  'society-mailbox',
  'society-rooms',
  'society-memory',
  'society-soul',
  'society-sandbox',
  'society-tools',
  'society-llm',
  'society-scheduler',
  'society-dsh-bridge',
]

const skipBuild = process.argv.includes('--patch-only')
fs.mkdirSync(OUT_DIR, { recursive: true })

if (!skipBuild) {
  const entryPoints = Object.fromEntries(
    PLUGINS.map((id) => [id, path.join(ROOT, 'plugins', id, 'src', 'index.ts')]),
  )
  await esbuild.build({
    entryPoints,
    outdir: OUT_DIR,
    entryNames: '[name]',
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    sourcemap: true,
    logLevel: 'info',
    external: [
      '@deepseek-ai/cordis',
      '@deepseek-ai/cosmokit',
      '@deepseek-ai/schemastery',
      '@deepseek-ai/cordis-plugin-loader',
      '@deepseek-ai/cordis-plugin-include',
    ],
    banner: {
      js: `/* society-chat dsh overlay — generated by scripts/build-dsh-overlay.mjs */\n`,
    },
  })
}

const abs = (id) => path.join(OUT_DIR, `${id}.js`).replace(/\\/g, '/')
const rel = (id) => `./lib/${id}.js`

function makePatch(nameFn, rootLabel) {
  const rows = PLUGINS.map((id) => {
    if (id === 'society-dsh-bridge') {
      return `    - id: ${id}
      name: '${nameFn(id)}'
      config:
        loadSeeds: true
        autoStartScheduler: false`
    }
    return `    - id: ${id}
      name: '${nameFn(id)}'`
  }).join('\n')
  return `# Generated / template for DeepSeek Harness out-of-tree society layer.
# root: ${rootLabel}
#
# Mount:
#   export SOCIETY_PROJECT_ROOT=<society-chat checkout>
#   npm run build:dsh-overlay
#   dsh --profile headless --dump-config --patch <this-file>
#
# Absolute paths required for file: plugins. Re-run build after clone.
# Default product path: docker compose / npm run society-live

- insert:
${rows}
`
}

fs.writeFileSync(PATCH_OUT, makePatch(abs, ROOT))
fs.writeFileSync(
  TEMPLATE_OUT,
  makePatch(rel, '__SOCIETY_ROOT__ (replace via npm run build:dsh-overlay)'),
)
console.log(`wrote ${PATCH_OUT}`)
console.log(`wrote ${TEMPLATE_OUT}`)
console.log(`lib: ${PLUGINS.map((p) => p + '.js').join(', ')}`)
